function audit_local_equilibrium_cuboid()
% Independently rerun exact equilibrium-containing geometry on all saved masks.
  started=tic(); here=fileparts(mfilename('fullpath')); model_dir=fileparts(here);
  saved=jsondecode(fileread(fullfile(model_dir,'geometry_equilibrium_local','summary.json')));
  report=struct('method','Independent MATLAB/Octave full equilibrium-containing cuboid search', ...
      'source_summary',fullfile(model_dir,'geometry_equilibrium_local','summary.json'), ...
      'containment_tolerance',1e-12,'volume_tie_relative_scale',1e-13, ...
      'all_raw_unstable_nodes_tested',true);
  for ii=1:numel(saved.cases)
    expected=saved.cases(ii); tag=num2str(expected.angle_deg);
    data=load(fullfile(model_dir,'vc_refined_5s',['classification_' tag 'deg.mat']));
    raw=data.PAPER_STABILITY3D.result; G=data.PAPER_STABILITY3D.cfg.grid;
    anchor=double(expected.equilibrium_anchor_vc_r_phi(:).');
    case_started=tic(); result=build_local_equilibrium_cuboid(raw.stable_mask,G,anchor);
    assert(result.valid,'Saved case unexpectedly has no containing cuboid');
    region_saved=load(fullfile(model_dir,'geometry_equilibrium_local',['region_local_' tag 'deg.mat']));
    region=region_saved.LOCAL_EQUILIBRIUM_REGION.region;
    lower=result.lower_bounds; upper=result.upper_bounds;
    unstable_inside=all(bsxfun(@ge,raw.unstable_points,lower-1e-10) & ...
                        bsxfun(@le,raw.unstable_points,upper+1e-10),2);
    vertices_stable=true;
    for k=1:8
      vertices_stable=vertices_stable && any(all(abs(bsxfun(@minus,raw.stable_points,result.vertices(k,:)))<1e-12,2));
    end
    expected_ties=sortrows(double(reshape(expected.maximum_volume_ties_grid_bound_indices_zero_based,[],6)),1:6);
    checks=struct('valid_matches',logical(result.valid)==logical(expected.valid), ...
      'bound_indices_exact_match',isequal(result.grid_bound_indices_zero_based,double(expected.grid_bound_indices_zero_based(:).')), ...
      'bounds_match',max(abs(result.bounds(:)-[double(expected.lower_bounds(:));double(expected.upper_bounds(:))]))<1e-14, ...
      'vertices_exact_match_region_mat',isequal(result.vertices,region.vertices), ...
      'volume_match',abs(result.volume-expected.volume)<1e-12, ...
      'all_tied_bound_tuples_exact_match',isequal(result.maximum_volume_ties_grid_bound_indices_zero_based,expected_ties), ...
      'tie_count_match',result.maximum_volume_tie_count==expected.maximum_volume_tie_count, ...
      'interval_count_match',result.positive_equilibrium_containing_roll_intervals_tested==expected.positive_equilibrium_containing_roll_intervals_tested, ...
      'rectangle_count_match',result.positive_equilibrium_containing_rectangles_evaluated==expected.positive_equilibrium_containing_rectangles_evaluated, ...
      'contains_own_equilibrium',result.contains_equilibrium, ...
      'all_grid_nodes_stable',result.all_grid_nodes_in_cuboid_stable, ...
      'all_eight_vertices_raw_stable',vertices_stable, ...
      'zero_raw_unstable_inside',nnz(unstable_inside)==0);
    values=struct2cell(checks);
    entry=struct('angle_deg',expected.angle_deg,'checks',checks,'all_checks_pass',all(cell2mat(values)), ...
       'result',result,'raw_unstable_nodes_tested',size(raw.unstable_points,1), ...
       'unstable_nodes_inside_inclusive',nnz(unstable_inside),'runtime_s',toc(case_started));
    if ii==1, report.cases=entry; else, report.cases(ii)=entry; end
    fprintf('local cuboid angle=%s: volume=%.17g, ties=%d, bad=%d, pass=%d\n', ...
       tag,result.volume,result.maximum_volume_tie_count,nnz(unstable_inside),entry.all_checks_pass);
  end
  report.all_checks_pass=all([report.cases.all_checks_pass]); report.runtime_s=toc(started);
  fid=fopen(fullfile(here,'local_cuboid_matlab_audit.json'),'w'); fprintf(fid,'%s\n',jsonencode(report)); fclose(fid);
  fprintf('all_checks_pass=%d, runtime_s=%.3f\n',report.all_checks_pass,report.runtime_s);
end
